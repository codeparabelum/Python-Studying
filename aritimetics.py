"""Operadores aritiméticos em python"""

adicao= 10 + 10
print('adição', adicao)

subtracao= 10 - 5
print('subtração', subtracao)

multiplicacao= 10 * 10
print('multiplicação', multiplicacao)

divisao= 100 / 12.0 #divisão comum
print('divisão', divisao)

divisao_inteira= 10 // 3
print('divisão inteira', divisao_inteira)

exponenciacao=  2 ** 4
print('exponenciação', exponenciacao)

modulo= 55 % 2 #resto da divisão
print('módulo',modulo)
"""se o resto de uma divisão for 0, então o número é 
divisível pelo outro. Pode ser usado BOOL 
para retornar essa resposta"""

print(10 % 8 ==0)
print(16 % 8 ==0)